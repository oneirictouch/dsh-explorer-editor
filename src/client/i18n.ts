/**
 * Dictionary + helpers for the dsh-explorer-editor UI.
 *
 * The `zh` / `en` dictionaries are registered under namespace `NS` by the
 * plugin entry (`index.tsx`). Components receive the bound translator as a
 * plain `(key) => string` function and localize every user-visible string.
 * Parameterized messages use `{placeholder}` tokens resolved by `format()` so
 * the dictionary stays static and testable.
 */

export const NS = 'dshFile';

/** The bound translator surface handed to UI components. */
export type Translator = (key: string) => string;

/** Interpolate `{placeholder}` tokens in a template string. */
export function format(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (token, key: string) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : token
  ));
}

